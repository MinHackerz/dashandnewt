def drive_root():
    hits = glob.glob(os.path.expanduser("~/Library/CloudStorage/GoogleDrive-*/My Drive"))
    if not hits:
        raise SystemExit("Google Drive for desktop is not set up on this Mac (no ~/Library/CloudStorage/GoogleDrive-*)")
    return os.path.join(hits[0], "render-jobs")


def notebook():
    cell = lambda src, kind: {"cell_type": kind, "metadata": {}, "source": src.splitlines(True),
                              **({"outputs": [], "execution_count": None} if kind == "code" else {})}
    cells = [cell(NOTEBOOK_CELLS[0], "markdown")] + [cell(c, "code") for c in NOTEBOOK_CELLS[1:]]
    return {"nbformat": 4, "nbformat_minor": 5, "cells": cells,
            "metadata": {"accelerator": "GPU", "colab": {"gpuType": "T4", "provenance": []},
                         "kernelspec": {"name": "python3", "display_name": "Python 3"}}}


def prepare(a):
    job = cj.load(a.job)
    frames = cj.missing(job, a.shots.split(",") if a.shots else None)
    frames = frames[:int(a.hours * 3600 / job.get("sec_per_frame", {}).get("T4", 110))]
    if not frames:
        return print("nothing to render")
    base = drive_root()
    d = os.path.join(base, a.job)
    os.makedirs(d, exist_ok=True)
    cj.bundle(job, os.path.join(d, "bundle.tar"))
    slim = {k: v for k, v in job.items() if not k.startswith("_")}
    slim.update(root=cj.ROOT, blender=cj.BLENDER, blender_url=cj.BLENDER_URL)
    json.dump(slim, open(os.path.join(d, "job.json"), "w"))
    json.dump(cj.runs(frames, 1), open(os.path.join(d, "work.json"), "w"))
    open(os.path.join(base, "CURRENT"), "w").write(a.job)
    json.dump(notebook(), open(os.path.join(base, "colab_render.ipynb"), "w"), indent=1)
    json.dump({"started": time.time(), "frames": len(frames)}, open(os.path.join(d, "session.json"), "w"))
    print(f"{len(frames)} frames queued for Colab in Drive/render-jobs/{a.job}; open render-jobs/colab_render.ipynb in Colab")


def collect(a):
    job = cj.load(a.job)
    d = os.path.join(drive_root(), a.job)
    n = cj.collect(os.path.join(d, "frames"), job) if os.path.isdir(os.path.join(d, "frames")) else 0
    s = json.load(open(os.path.join(d, "session.json"))) if os.path.exists(os.path.join(d, "session.json")) else {}
    hours = (time.time() - s["started"]) / 3600 if s else 0.0
    cj.ledger_add("colab", a.job, "T4", n, hours)
    print(f"colab: filed {n} new frames into {job['local_out']}")
    if n and not cj.missing(job):
        shutil.rmtree(d)  # all done: free the Drive space


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["prepare", "collect"])
    ap.add_argument("job")
    ap.add_argument("--hours", type=float, default=3.0)
    ap.add_argument("--shots", default="")
    a = ap.parse_args()
    prepare(a) if a.cmd == "prepare" else collect(a)
