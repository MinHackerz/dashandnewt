"""Render a job's missing frames on Kaggle Notebooks (free: GPU "T4 x2", ~30 GPU-hours a week, 12 h per session).
Normally started by tools/render/cloud.py when Modal's free $30 for the month is used up.

    .venv-modal/bin/python tools/render/kaggle_render.py <job> [--hours 11] [--shots a,b]

1. the job's files go up as a PRIVATE Kaggle dataset `<you>/render-<job>` (created, or a new version);
2. a private GPU script kernel `<you>/render-<job>-gpu` installs Blender 5.2.3, mounts the files at the Mac's absolute
   project path and renders on both T4s at once (one Blender per GPU, OptiX), stopping cleanly before the session
   limit; finished frames are the kernel's output;
3. this script waits, downloads the output, files new frames into the job's output folder and logs the GPU hours
   (Kaggle counts session wall-clock time) to out/render_logs/cloud_ledger.csv.
Needs the Kaggle API token (Kaggle → Settings → API → Create New Token), placed by you; this script never reads it.
Kaggle needs a phone-verified account for GPUs and internet access in notebooks.
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cloudjob as cj  # noqa: E402

KAGGLE = os.path.join(cj.ROOT, ".venv-modal/bin/kaggle")
STAGE = os.path.join(cj.ROOT, "out/cloud/kaggle")

KERNEL = r'''
# generated by tools/render/kaggle_render.py: renders WORK on both GPUs, then leaves frames in /kaggle/working/frames
import glob, json, os, subprocess, sys, tarfile, threading, time
JOB = json.loads(%(job)r); WORK = json.loads(%(work)r); ROOT = %(root)r; DEADLINE = time.time() + %(budget)d
BL = "%(blender)s"
subprocess.run(["wget", "-q", "%(url)s", "-O", "/tmp/b.tar.xz"], check=True)
subprocess.run(["tar", "-xJf", "/tmp/b.tar.xz", "-C", "/opt"], check=True)
for lib in ["libxrender1", "libxi6", "libxkbcommon0", "libsm6", "libxxf86vm1", "libxfixes3", "libegl1"]:
    subprocess.run(["bash", "-c", f"dpkg -s {lib} >/dev/null 2>&1 || (apt-get -qq update >/dev/null; apt-get -qq install -y {lib} >/dev/null)"])
os.makedirs(ROOT, exist_ok=True)
tars = glob.glob("/kaggle/input/**/bundle.tar", recursive=True)
if tars:
    tarfile.open(tars[0]).extractall(ROOT)
else:  # Kaggle may have unpacked the archive already
    src = glob.glob("/kaggle/input/**/" + JOB["blend"], recursive=True)[0][: -len(JOB["blend"])]
    subprocess.run(["cp", "-a", src + ".", ROOT], check=True)
OUT = "/kaggle/working/frames"
os.makedirs(OUT, exist_ok=True)
print(subprocess.run(["nvidia-smi", "-L"], capture_output=True, text=True).stdout, flush=True)

def worker(gpu, runs):
    for shot, f0, f1 in runs:
        if time.time() > DEADLINE:
            return
        env = dict(os.environ, CUDA_VISIBLE_DEVICES=str(gpu), **JOB["env"])
        env.update({JOB["frames_env"]: f"{f0}-{f1}", JOB["out_env"]: OUT, JOB["compute_env"]: "OPTIX"})
        cmd = [f"/opt/{BL}/blender", "-b", os.path.join(ROOT, JOB["blend"]), "--python",
               os.path.join(ROOT, JOB["script"]), "--", *JOB["args"], shot]
        p = subprocess.Popen(cmd, env=env, cwd=ROOT, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        for line in p.stdout:
            if line.startswith(("FRAME", "Traceback")) or "Error" in line:
                print(f"[gpu{gpu}] {line.rstrip()}", flush=True)
            if time.time() > DEADLINE:  # stop before the session limit; finished frames are kept
                p.kill(); break
        p.wait()

ts = [threading.Thread(target=worker, args=(g, r)) for g, r in enumerate(WORK)]
[t.start() for t in ts]; [t.join() for t in ts]
print("KAGGLE RENDER DONE", len(glob.glob(OUT + "/*/*.png")), "frames", flush=True)
'''


def kaggle(*a, capture=True):
    r = subprocess.run([KAGGLE, *a], capture_output=capture, text=True)
    if r.returncode:
        raise SystemExit(f"kaggle {' '.join(a)} failed:\n{r.stdout}\n{r.stderr}")
    return r.stdout


def username():
    for line in kaggle("config", "view").splitlines():
        if line.strip().startswith("- username:"):
            return line.split(":", 1)[1].strip()
    raise SystemExit("Kaggle is not logged in: put your API token in place first (see this file's docstring)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("job")
    ap.add_argument("--hours", type=float, default=11.0, help="render budget for this session (Kaggle cap: 12 h)")
    ap.add_argument("--shots", default="")
    a = ap.parse_args()
    job = cj.load(a.job)
    user = username()
    frames = cj.missing(job, a.shots.split(",") if a.shots else None)
    spf = job.get("sec_per_frame", {}).get("T4", 110)
    fit = int(a.hours * 3600 * 2 / spf)  # two T4s
    frames = frames[:fit]
    if not frames:
        return print("nothing to render")
    runs = cj.runs(frames, 2)
    work = [[], []]
    for i, r in enumerate(runs):  # runs come in plan order, ~half the frames per GPU
        work[0 if sum(x[2] - x[1] + 1 for x in runs[:i]) < len(frames) / 2 else 1].append(r)
    print(f"{a.job}: {len(frames)} frames on Kaggle T4×2 (~{len(frames) * spf / 7200:.1f} h): {work}", flush=True)

    ds_dir, k_dir = os.path.join(STAGE, a.job, "dataset"), os.path.join(STAGE, a.job, "kernel")
    shutil.rmtree(os.path.join(STAGE, a.job), ignore_errors=True)
    os.makedirs(ds_dir), os.makedirs(k_dir)
    cj.bundle(job, os.path.join(ds_dir, "bundle.tar"))
    ds = f"{user}/render-{a.job}"
    json.dump({"title": f"render-{a.job}", "id": ds, "licenses": [{"name": "other"}]},
              open(os.path.join(ds_dir, "dataset-metadata.json"), "w"))
    exists = subprocess.run([KAGGLE, "datasets", "status", ds], capture_output=True, text=True).returncode == 0
    if exists:
        kaggle("datasets", "version", "-p", ds_dir, "-m", time.strftime("%Y-%m-%d %H:%M"))
    else:
        kaggle("datasets", "create", "-p", ds_dir)  # private unless --public
    for _ in range(120):
        if "ready" in subprocess.run([KAGGLE, "datasets", "status", ds], capture_output=True, text=True).stdout:
            break
        time.sleep(15)
    job_slim = {k: v for k, v in job.items() if not k.startswith("_")}
    code = KERNEL % dict(job=json.dumps(job_slim), work=json.dumps(work), root=cj.ROOT, budget=int(a.hours * 3600),
                         blender=cj.BLENDER, url=cj.BLENDER_URL)
    open(os.path.join(k_dir, "script.py"), "w").write(code)
    kid = f"{user}/render-{a.job}-gpu"
    json.dump({"id": kid, "title": f"render-{a.job}-gpu", "code_file": "script.py", "language": "python",
               "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
               "dataset_sources": [ds], "competition_sources": [], "kernel_sources": []},
              open(os.path.join(k_dir, "kernel-metadata.json"), "w"))
    t0 = time.time()
    kaggle("kernels", "push", "-p", k_dir, "--accelerator", "NvidiaTeslaT4", "-t", str(int(a.hours * 3600 + 1800)))
    while True:
        time.sleep(120)
        st = subprocess.run([KAGGLE, "kernels", "status", kid], capture_output=True, text=True).stdout.lower()
        print(time.strftime("%H:%M"), st.strip(), flush=True)
        if any(w in st for w in ("complete", "error", "cancel")):
            break
    hours = (time.time() - t0) / 3600
    out = os.path.join(STAGE, a.job, "output")
    kaggle("kernels", "output", kid, "-p", out, "--force", capture=False)
    n = cj.collect(os.path.join(out, "frames"), job) if os.path.isdir(os.path.join(out, "frames")) else 0
    cj.ledger_add("kaggle", a.job, "T4x2", n, hours)
    print(f"kaggle: filed {n} new frames into {job['local_out']} ({hours:.2f} session hours)")
    if "error" in st:
        raise SystemExit("the Kaggle run ended with an error: see `kaggle kernels output` log in " + out)


if __name__ == "__main__":
    main()
